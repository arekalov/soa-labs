#!/usr/bin/env bash
#
# Валит ВСЮ службу Starship через балансировщик (порт 27343).
# Оба узла урезаны (пул 2, таймаут 1 с), поэтому HAProxy переливать некуда:
# под нагрузкой оба уходят в DOWN, и клиент получает 503.
# Запускать с ноутбука; curl крутится на самом helios. Данные не меняет.
#
#   ./kill-balancer.sh        # 30 потоков
#   ./kill-balancer.sh 40     # сильнее

C="${1:-30}"
N=$(( C * 10 ))

echo "Бью в балансировщик (27343): $N запросов по $C одновременно — валю оба узла"
ssh ifmo "seq $N | xargs -P $C -I{} \
  curl -s -k -o /dev/null --max-time 20 -w '%{http_code}\n' \
  'https://127.0.0.1:27343/starship?size=50' | sort | uniq -c"
echo "200 — успех, 503 — балансировщику некуда слать (оба узла легли),"
echo "500 — пул узла исчерпан, 000 — таймаут"
